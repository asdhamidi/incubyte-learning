"""Data tests for the staging layer. Each query returns the offending rows, so an empty
result means the check passed. The SQL is plain enough to run on DuckDB and Snowflake."""

import textwrap

STAGING_CHECKS = {
    "id_not_null": "SELECT * FROM stg_games WHERE id IS NULL",
    "id_unique": """
        SELECT id, COUNT(*) AS n FROM stg_games GROUP BY id HAVING COUNT(*) > 1""",
    "rated_not_null": "SELECT * FROM stg_games WHERE rated IS NULL",
    "ratings_not_null": """
        SELECT * FROM stg_games WHERE white_rating IS NULL OR black_rating IS NULL""",
    "ratings_positive": """
        SELECT * FROM stg_games WHERE white_rating <= 0 OR black_rating <= 0""",
    "rows_match_raw": """
        SELECT * FROM (
            SELECT (SELECT COUNT(*) FROM stg_games) AS staging_rows,
                   (SELECT COUNT(DISTINCT id) FROM raw_games) AS raw_games_ids
        ) t
        WHERE staging_rows <> raw_games_ids""",
}


def run_check(con, name):
    return con.execute(STAGING_CHECKS[name]).fetchall()


# The data quality check. It blocks the summary when it fails, see docs/dq_failure_plan.md.
# Validity: the summary only counts 'white' and 'black', so any other spelling of the winner
# would be left out of the metric silently. NULL needs its own test, because
# NULL NOT IN (...) is never true.
DQ_CHECKS = {
    "winner_accepted_values": """
        SELECT winner, COUNT(*) AS n
        FROM stg_games
        WHERE winner IS NULL OR winner NOT IN ('white', 'black', 'draw')
        GROUP BY winner
        ORDER BY n DESC, winner""",
}


def run_dq_check(con, name):
    """The offending values and how many rows have each. An empty list means it passed."""
    return con.execute(DQ_CHECKS[name]).fetchall()


def export_checks_sql():
    """Every check as one SQL script for Snowflake, so the queries CI tests are the ones run there.

    Written to sql/snowflake/04_checks.sql by `python -m games_pipeline.checks`.
    """
    parts = [
        "-- Generated by `python -m games_pipeline.checks`. Do not edit by hand.",
        "-- Each query returns the offending rows. Zero rows means the check passed.",
        "-- Run after sql/stg_games.sql and before sql/games_summary.sql.",
    ]
    for label, checks in (
        ("staging data test", STAGING_CHECKS),
        ("data quality check, blocks the summary", DQ_CHECKS),
    ):
        for name, query in checks.items():
            query_text = textwrap.dedent(query).strip()
            parts.append(f"\n-- {label}: {name}\n{query_text};")
    return "\n".join(parts) + "\n"


if __name__ == "__main__":
    from pathlib import Path

    target = Path(__file__).resolve().parents[2] / "sql" / "snowflake" / "04_checks.sql"
    target.write_text(export_checks_sql(), newline="\n")
    print(f"wrote {target}")
